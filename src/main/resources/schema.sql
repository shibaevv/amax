create schema if not exists public;
use public;

create table if not exists currency (
  currency_code char(3) not null,
  currency_title varchar(255) not null,
  currency_base char(1),
  primary key (currency_code)
);

create table if not exists amax_rule_input_type (
  type_id int not null,
  type_code varchar(32) not null,
  type_title varchar(255) not null,
  primary key (type_id)
);

create table if not exists series_data_key (
  key_id bigint generated by default as identity,
  key_name varchar(64) not null,
  key_title varchar(255),
  key_type char(1) not null,
  input_type int,
  output_key_id bigint,
  currency_code char(3) not null,
  constraint series_data_key_fk1 foreign key (output_key_id) references series_data_key (key_id),
  constraint series_data_key_fk2 foreign key (currency_code) references currency (currency_code),
  primary key (key_id)
);
create unique index if not exists series_data_key_uk1 on series_data_key (key_name);

-- drop table series_data;
create table if not exists series_data (
  series_data_id bigint generated by default as identity,
  series_data_date date not null,
  key_id bigint not null,
  series_data_value numeric(38,2) not null,
  currency_base char(3) not null,
  currency_code char(3) not null,
  series_data_title varchar(255),
  constraint series_data_fk1 foreign key (key_id) references series_data_key (key_id),
  constraint series_data_fk2 foreign key (currency_base) references currency (currency_code),
  constraint series_data_fk3 foreign key (currency_code) references currency (currency_code),
  primary key (series_data_id)
);
create index if not exists series_data_idx1 on series_data_key (key_id);
create unique index if not exists series_data_uk1 on series_data (series_data_date, key_id);

create table if not exists amax_rule (
  id bigint generated by default as identity,
  expression varchar(1024) not null,
  primary key (id)
);

create table if not exists amax_rule_input (
  id bigint generated by default as identity,
  name varchar(255) not null,
  rule_id bigint,
  key_id bigint,
  output_key_id bigint,
  output_type int not null,
  constraint amax_rule_input_fk1 foreign key (rule_id) references amax_rule (id),
  constraint amax_rule_input_fk2 foreign key (key_id) references series_data_key (key_id),
  constraint amax_rule_input_fk3 foreign key (output_key_id) references series_data_key (key_id),
  constraint amax_rule_input_fk4 foreign key (output_type) references amax_rule_input_type (type_id),
  primary key (id)
);
